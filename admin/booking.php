function sortBy(col){
    sessionStorage.setItem('booking_scrollY', window.scrollY);
    
    const params = new URLSearchParams(window.location.search);
    const currentSort = params.get('sort') || 'tanggal';
    const currentOrder = params.get('order') || 'DESC';
    
    if(currentSort === col){
        params.set('order', currentOrder === 'ASC' ? 'DESC' : 'ASC');
    } else {
        params.set('sort', col);
        params.set('order', 'ASC');
    }
    
    window.location.href = 'booking.php?' + params.toString() + '#allBookings';
}

