// ===== DATE TAB SWITCHING - AJAX =====
function switchDate(dateStr, tabEl){
    // Update active tab UI
    document.querySelectorAll('.date-tab').forEach(t => t.classList.remove('active'));
    tabEl.classList.add('active');
    
    // Show loading
    const grid = document.getElementById('scheduleGrid');
    grid.innerHTML = `
        <div class="schedule-loading">
            <i class="fas fa-spinner fa-spin"></i>
            <p>Loading schedule...</p>
        </div>
    `;
    
    // Fetch via AJAX
    fetch('booking.php?ajax_schedule=1&schedule_date=' + dateStr)
        .then(response => response.text())
        .then(html => {
            grid.innerHTML = html;
            showToast('info', 'Schedule Updated', 'Showing barbers on duty for ' + dateStr);
        })
        .catch(err => {
            grid.innerHTML = `
                <div style="grid-column:1/-1;text-align:center;padding:40px;color:var(--text-muted);">
                    <i class="fas fa-exclamation-circle" style="font-size:48px;margin-bottom:16px;display:block;opacity:0.5;"></i>
                    <h3 style="font-family:'Space Grotesk',sans-serif;font-size:18px;color:var(--text-secondary);margin-bottom:8px;">Failed to load</h3>
                    <p>Please refresh the page.</p>
                </div>
            `;
        });
}

